function currentPage() {
  return document.body.dataset.page || "home";
}

function initialLanguage() {
  const url = new URL(window.location.href);
  const q = url.searchParams.get("lang");
  if (q === "en" || q === "ru") return q;

  const saved = localStorage.getItem("site-language");
  if (saved === "en" || saved === "ru") return saved;

  return navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
}

function lookup(language, key) {
  const page = currentPage();
  return copy[language]?.[page]?.[key] ?? copy[language]?.common?.[key] ?? "";
}

function syncLinks(language) {
  document.querySelectorAll("a[data-preserve-lang]").forEach((link) => {
    const href = link.getAttribute("href");
    if (!href || href.startsWith("http")) return;
    const url = new URL(href, window.location.href);
    url.searchParams.set("lang", language);
    link.href = url.pathname + url.search + url.hash;
  });
}

function setLanguage(language, updateUrl = true) {
  if (!copy[language]) return;

  document.body.classList.add("language-changing");

  setTimeout(() => {
    document.documentElement.lang = language;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const value = lookup(language, el.dataset.i18n);
      if (value !== "") el.innerHTML = value;
    });

    const title = lookup(language, "title");
    const description = lookup(language, "description");

    if (title) document.title = title;
    if (description) {
      const meta = document.querySelector('meta[name="description"]');
      if (meta) meta.setAttribute("content", description);
    }

    document.querySelectorAll("[data-language]").forEach((button) => {
      button.setAttribute(
        "aria-pressed",
        button.dataset.language === language ? "true" : "false"
      );
    });

    localStorage.setItem("site-language", language);
    syncLinks(language);

    if (updateUrl) {
      const url = new URL(window.location.href);
      url.searchParams.set("lang", language);
      history.replaceState({}, "", url);
    }

    document.body.classList.remove("language-changing");
  }, 90);
}

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

document.querySelectorAll("[data-project-tab]").forEach((button) => {
  button.addEventListener("click", () => {
    const target = button.dataset.projectTab;

    document.querySelectorAll("[data-project-tab]").forEach((tab) => {
      tab.setAttribute("aria-selected", tab === button ? "true" : "false");
    });

    document.querySelectorAll("[data-project-panel]").forEach((panel) => {
      panel.hidden = panel.dataset.projectPanel !== target;
    });
  });
});

setLanguage(initialLanguage(), false);
